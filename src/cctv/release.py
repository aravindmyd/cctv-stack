def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _copy_member(repo: Path, relative: str, destination: Path) -> Path:
    source = Path(repo) / relative
    if not source.is_file():
        raise ReleaseError(
            f"{relative} is on the bundle allowlist but is not in the repository. A bundle with a "
            f"hole in it is worse than no bundle, so this aborts."
        )
    target = destination / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, target)
    shutil.copymode(source, target)
    return target


def assemble(
    *,
    repo: Path,
    out_dir: Path,
    images: Mapping[str, str],
    frigate_version: str,
    frigate_contract_verified: str,
    frigate_images: Mapping[str, str],
    mosquitto_image: str,
    version: str | None = None,
) -> BundleResult:
    """Write `cctv-stack-<version>.tar.gz` and `SHA256SUMS` into `out_dir`."""
    repo = Path(repo)
    out_dir = Path(out_dir)
    resolved = version or bundle_version(repo)
    name = f"cctv-stack-{resolved}"

    with tempfile.TemporaryDirectory() as scratch:
        staging = Path(scratch) / name
        staging.mkdir()
        (staging / "VERSION").write_text(f"{resolved}\n", encoding="utf-8")

        for relative in BUNDLE_ALLOWLIST:
            if relative == "compose.yml":
                continue  # derived below, from the same file
            _copy_member(repo, relative, staging)

        source_compose = (repo / "compose.yml").read_text(encoding="utf-8")
        (staging / "compose.yml").write_text(derive_compose(source_compose), encoding="utf-8")

        manifest = versions_manifest(
            version=resolved,
            repo=repo,
            images=images,
            frigate_version=frigate_version,
            frigate_contract_verified=frigate_contract_verified,
            frigate_images=frigate_images,
            mosquitto_image=mosquitto_image,
        )
        (staging / "versions.yml").write_text(
            yaml.safe_dump(manifest, sort_keys=False, default_flow_style=False), encoding="utf-8"
        )

        services = cctv_services(source_compose)
        for architecture in ("amd64", "arm64"):
            (staging / f"compose.override.{architecture}.yml").write_text(
                override_for(manifest, arch=architecture, services=services), encoding="utf-8"
            )

        files = sorted(
            path.relative_to(staging).as_posix() for path in staging.rglob("*") if path.is_file()
        )
        digests = {relative: _sha256(staging / relative) for relative in files}
        checksum_text = "".join(
            f"{digest}  {relative}\n" for relative, digest in sorted(digests.items())
        )
        (staging / "SHA256SUMS").write_text(checksum_text, encoding="utf-8")
        digests["SHA256SUMS"] = _sha256(staging / "SHA256SUMS")

        out_dir.mkdir(parents=True, exist_ok=True)
        archive = out_dir / f"{name}.tar.gz"
        with tarfile.open(archive, "w:gz") as tar:
            # `arcname` keeps the versioned directory at the top level, so extracting with
            # `--strip-components=1` into `/opt/cctv` is the documented flow.
            tar.add(staging, arcname=name)
        checksums = out_dir / "SHA256SUMS"
        shutil.copyfile(staging / "SHA256SUMS", checksums)

    return BundleResult(
        version=resolved,
        directory=out_dir / name,
        archive=archive,
        checksums=checksums,
        files=tuple(sorted(digests)),
        bytes_written=archive.stat().st_size,
        sha256=digests,
    )


