#: The override files, one per architecture, generated with the bundle and *chosen* at install
#: time by `install.sh`.
#:
#: Shipped rather than generated on the host, and this is the one place this module departs from
#: `packaging.md` §2.2's wording. Generating them on the host means either parsing YAML in bash —
#: a shape assumption that fails silently — or pulling the image first so a container can parse
#: the file that says which image to pull. Shipping two small files removes both problems: the
#: *content* is per-release and verified with the rest of the bundle, and the *choice* is per-host
#: and is a single `cp`.
OVERRIDE_FILES = ("compose.override.amd64.yml", "compose.override.arm64.yml")

#: Files generated by this tool rather than copied. Listed so a reviewer can see the whole
#: contents of a bundle in two lists.
GENERATED = ("VERSION", "compose.yml", "versions.yml", "SHA256SUMS", *OVERRIDE_FILES)

PYTHON_VERSION = "3.12"


class ReleaseError(RuntimeError):
    """A release that must not be published."""


@dataclass(frozen=True, slots=True)
class BundleResult:
    version: str
    directory: Path
    archive: Path
    checksums: Path
    files: tuple[str, ...] = ()
    bytes_written: int = 0
    sha256: Mapping[str, str] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "version": self.version,
            "directory": str(self.directory),
            "archive": str(self.archive),
            "checksums": str(self.checksums),
            "files": list(self.files),
            "bytes_written": self.bytes_written,
        }


@dataclass(frozen=True, slots=True)
class InspectResult:
    ok: bool
    version: str = ""
    files: tuple[str, ...] = ()
    problems: tuple[str, ...] = ()
    digests: Mapping[str, str] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "ok": self.ok,
            "version": self.version,
            "files": list(self.files),
            "problems": list(self.problems),
            "digests": dict(self.digests),
        }


