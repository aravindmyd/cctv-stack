def versions_manifest(
    *,
    version: str,
    repo: Path,
    images: Mapping[str, str],
    frigate_version: str,
    frigate_contract_verified: str,
    frigate_images: Mapping[str, str],
    mosquitto_image: str,
) -> dict[str, Any]:
    """The manifest an installer reads, and the two gates that belong with it.

    `api_contract_verified` is compared against `frigate_version` **here**, so a release cannot
    carry a Frigate version nobody ran the integration checklist against (`lld/09`). The other
    gate is structural: both architectures must be present, because they are different images
    and an arm64 site that silently fell back to amd64 would fail in a way that looks like a
    camera problem.
    """
    for arch in ("amd64", "arm64"):
        if not (images.get(arch) or "").strip():
            raise ReleaseError(
                f"no image digest for {arch}. Both architectures are recorded separately because "
                f"they are different images (ADR-0014)."
            )
        if "@sha256:" not in str(images[arch]):
            raise ReleaseError(
                f"the {arch} cctv image is {images[arch]!r}, which is not pinned by digest. "
                f"A tag can be moved; a digest cannot."
            )
        if not (frigate_images.get(arch) or "").strip():
            raise ReleaseError(f"no Frigate image for {arch}.")

    if frigate_contract_verified != frigate_version:
        raise ReleaseError(
            f"Frigate {frigate_version!r} is being released, but the integration checklist was "
            f"last verified against {frigate_contract_verified!r}. Re-run "
            f"contracts/frigate-integration.md §9 and update both values together (lld/09)."
        )

    return {
        "cctv_stack": version,
        "schema": {
            "database": database_schema_version(repo),
            # `cameras.yml`'s key set. Bumped when a key is added or its meaning changes, so an
            # installer can tell a file that predates the current schema.
            "config": 1,
        },
        "frigate": {
            "version": frigate_version,
            "api_contract_verified": frigate_contract_verified,
            "images": dict(frigate_images),
        },
        "images": {
            "mosquitto": mosquitto_image,
            "cctv": dict(images),
        },
        "python": PYTHON_VERSION,
    }


def cctv_services(compose_text: str) -> tuple[str, ...]:
    """The services that run our image, derived from the compose file itself.

    Any service whose `image:` refers to `${CCTV_IMAGE...}` is ours. Derived rather than listed so
    that adding a service to `compose.yml` cannot leave it unpinned in a release — the failure
    would be a container quietly running whatever `cctv-stack:local` happened to be on the host.
    """
    document = yaml.safe_load(compose_text) or {}
    found = [
        name
        for name, body in _services(document).items()
        if isinstance(body, Mapping) and "CCTV_IMAGE" in str(body.get("image") or "")
    ]
    if not found:
        raise ReleaseError(
            "no service in compose.yml runs ${CCTV_IMAGE}, so there is nothing to pin. A release "
            "whose override pins nothing runs whatever image the host happens to have."
        )
    return tuple(sorted(found))


def override_for(
    manifest: Mapping[str, Any],
    *,
    arch: str,
    services: Sequence[str],
    target: str | None = None,
) -> str:
    """`compose.override.yml` pinning every service's image to this architecture's digest.

    **Each service must be named explicitly.** `x-cctv-image` in `compose.yml` is an extension key
    Compose ignores, and a YAML anchor does not resolve across two merged files — so an override
    that merely redefined the anchor would pin nothing at all, and the site would run whatever
    `cctv-stack:local` was on the host. Every service therefore takes its image from one anchor
    *inside the override file*, which keeps the digest in exactly one place and makes
    `install.sh --registry` a one-line rewrite rather than a loop over a list that can grow.

    `target` is the mirrored registry *path* (`registry.site.local/cctv-stack`); leaving it
    `None` keeps the reference exactly as recorded, which is the normal case.
    """
    images = manifest.get("images") or {}
    cctv = (images.get("cctv") or {}).get(arch)
    frigate = ((manifest.get("frigate") or {}).get("images") or {}).get(arch)
    mosquitto = images.get("mosquitto")
    if not cctv or not frigate or not mosquitto:
        raise ReleaseError(f"versions.yml has no complete image set for {arch}.")
    if not services:
        raise ReleaseError(f"no cctv services to pin for {arch}.")

    pinned = cctv if target is None else target_from(cctv, target)
    lines = [
        "# Written by install.sh from versions.yml. Do not edit: it records the digests this",
        "# release was signed for, and an edited pin is not the artefact anyone verified.",
        "x-cctv-image-override: &cctv-image-override",
        f"  image: {pinned}",
        "services:",
    ]
    for name in services:
        lines.append(f"  {name}:")
        lines.append("    <<: *cctv-image-override")
    lines.append("  mosquitto:")
    lines.append(f"    image: {mosquitto}")
    lines.append("  frigate:")
    lines.append(f"    image: {frigate}")
    return "\n".join(lines) + "\n"


def target_from(reference: str, target: str) -> str:
    """`--registry` rewrites the host and keeps the digest.

    Keeping the digest is the point: a mirror serving "the same version" retagged is not the same
    bytes, and the signature covers the digest.
    """
    _, _, tail = reference.partition("@")
    if not tail:
        raise ReleaseError(f"{reference!r} has no digest to preserve when rewriting the registry.")
    return f"{target}@{tail}"


