# Verification of the built artefact
# ---------------------------------------------------------------------------------------


def inspect(archive: Path) -> InspectResult:
    """Check a *built* bundle: no forbidden path, checksums that match, no `build:`.

    This is the check that would have caught every bundle mistake worth catching, so it runs on
    the artefact rather than on the intent. `inspect` returning `ok=False` must fail the release.
    """
    archive = Path(archive)
    problems: list[str] = []
    if not archive.is_file():
        return InspectResult(ok=False, problems=(f"no such archive: {archive}",))

    with tempfile.TemporaryDirectory() as scratch:
        with tarfile.open(archive, "r:gz") as tar:
            members = [member for member in tar.getmembers() if member.isfile()]
            for member in members:
                parts = Path(member.name).parts[1:]  # drop the versioned directory
                if Path(member.name).is_absolute() or ".." in member.name:
                    problems.append(f"unsafe path: {member.name}")
                    continue
                for forbidden in FORBIDDEN_IN_BUNDLE:
                    if parts[: len(Path(forbidden).parts)] == Path(forbidden).parts:
                        problems.append(f"forbidden path in bundle: {member.name}")
            tar.extractall(scratch, filter="data")

        root = Path(scratch) / Path(archive.name.removesuffix(".tar.gz"))
        if not root.is_dir():
            return InspectResult(ok=False, problems=(*problems, "no top-level directory"))

        version = ""
        version_file = root / "VERSION"
        if version_file.is_file():
            version = version_file.read_text(encoding="utf-8").strip()
        else:
            problems.append("VERSION is missing")

        expected = f"cctv-stack-{version}.tar.gz"
        if version and archive.name != expected:
            problems.append(f"{archive.name} does not match VERSION {version!r}")

        checksums = _read_checksums(root / "SHA256SUMS")
        if checksums is None:
            problems.append("SHA256SUMS is missing or malformed")
        else:
            for relative, digest in checksums.items():
                candidate = root / relative
                if not candidate.is_file():
                    problems.append(f"SHA256SUMS names {relative}, which is not in the archive")
                    continue
                if _sha256(candidate) != digest:
                    problems.append(f"{relative} does not match its checksum")

        compose_file = root / "compose.yml"
        if compose_file.is_file():
            try:
                compose = yaml.safe_load(compose_file.read_text(encoding="utf-8")) or {}
            except yaml.YAMLError as exc:
                problems.append(f"compose.yml does not parse: {exc}")
            else:
                if not isinstance(compose, Mapping):
                    problems.append("compose.yml is not a mapping")
                elif "build" in (compose.get("x-cctv-image") or {}):
                    problems.append("compose.yml still defines a build: block")
                else:
                    for name, body in _services(compose).items():
                        if isinstance(body, Mapping) and "build" in body:
                            problems.append(f"service {name} still has a build: block")
        else:
            problems.append("compose.yml is missing")

        manifest: Mapping[str, Any] = {}
        manifest_file = root / "versions.yml"
        if manifest_file.is_file():
            try:
                loaded = yaml.safe_load(manifest_file.read_text(encoding="utf-8")) or {}
            except yaml.YAMLError as exc:
                problems.append(f"versions.yml does not parse: {exc}")
            else:
                if isinstance(loaded, Mapping):
                    manifest = loaded
                else:
                    problems.append("versions.yml is not a mapping")
        else:
            problems.append("versions.yml is missing")

        # Both overrides pinned, and pinned to what `versions.yml` says they pin. That agreement
        # is the invariant: an arm64 site running an amd64 digest fails in a way that looks like
        # a camera problem, and a mismatch here is the only place it is cheap to notice.
        ours: tuple[str, ...] = ()
        if compose_file.is_file():
            try:
                ours = cctv_services(compose_file.read_text(encoding="utf-8"))
            except (ReleaseError, yaml.YAMLError):
                ours = ()

        recorded = (manifest.get("images") or {}).get("cctv") or {}
        for architecture in ("amd64", "arm64"):
            override = root / f"compose.override.{architecture}.yml"
            if not override.is_file():
                problems.append(f"compose.override.{architecture}.yml is missing")
                continue
            text = override.read_text(encoding="utf-8")
            try:
                document = yaml.safe_load(text) or {}
            except yaml.YAMLError as exc:
                problems.append(f"compose.override.{architecture}.yml does not parse: {exc}")
                continue
            pinned = [
                str(service.get("image", ""))
                for service in (document.get("services") or {}).values()
                if isinstance(service, Mapping)
            ]
            # Every one of our services must actually carry a digest. An override that redefined
            # the anchor without merging it into each service would pin nothing, and Compose
            # ignores `x-cctv-image`, so nothing else would notice.
            materialised = [
                str(service.get("image", ""))
                for name, service in (document.get("services") or {}).items()
                if isinstance(service, Mapping) and name in ours
            ]
            if ours and len(materialised) != len(ours):
                problems.append(
                    f"compose.override.{architecture}.yml does not pin every cctv service: "
                    f"expected {', '.join(sorted(ours))}"
                )
            if not pinned or any("@sha256:" not in image for image in pinned):
                problems.append(
                    f"compose.override.{architecture}.yml does not pin every image by digest"
                )
            expected = recorded.get(architecture)
            if expected and str(expected) not in text:
                problems.append(
                    f"compose.override.{architecture}.yml does not pin the digest "
                    f"versions.yml records for {architecture}"
                )

        files = sorted(
            path.relative_to(root).as_posix() for path in root.rglob("*") if path.is_file()
        )

    return InspectResult(
        ok=not problems,
        version=version,
        files=tuple(files),
        problems=tuple(problems),
        digests={key: value for key, value in (checksums or {}).items()},
    )


def _read_checksums(path: Path) -> dict[str, str] | None:
    if not path.is_file():
        return None
    digests: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        digest, _, relative = line.partition("  ")
        if len(digest) != 64 or not relative:
            return None
        digests[relative.strip()] = digest
    return digests or None


