"""Build the release bundle (`packaging.md` §2.1, §2.2, §5, §6).

A site receives a bundle, not a git checkout: `install.sh` stays the entry point, but what sits
beside it is a fixed set of files with a version in the filename and a checksum per file. This
module is the only thing that produces one, so "what ships" is a list you can read rather than a
list you can infer.

Four decisions, each about a way this goes wrong:

**An allowlist, never `git archive`.** `git archive` ships tests, the synthetic harness, and
whatever a future contributor commits by accident. The list below fails closed: a file that is
not named does not ship, and a named file that is missing aborts the build rather than producing
a bundle with a hole in it. `inspect` then re-checks the *built* artefact, because the check that
matters is on the thing you are about to publish, not on the code that built it.

**The shipped `compose.yml` has no `build:`.** The repository's is correct for development and
wrong for a site: the bundle contains no `Dockerfile` and no `src/`, so a compose file that can
try to build turns a missing image into a confusing build failure instead of "the image this
release pins is not there". Derived from the real file rather than forked, and verified by
re-parsing the result — a text edit keeps the comments an operator reads, and parsing keeps the
edit honest.

**`versions.yml` records digests, not tags.** A tag can be moved; a digest cannot
([ADR-0014](../../../internal/adr/0014-pinned-image-digests.md)). The two architectures are
recorded separately because they are different images, and `api_contract_verified` is compared
against the Frigate version here rather than trusted — that comparison is the gate `lld/09` says
blocks a release.

**Nothing here signs anything.** Signing is `cosign` in the workflow, with the OIDC identity that
only a CI run has. Splitting it that way means this tool is testable without a network, a key, or
a GitHub token, and the part that is *not* testable locally is as small as possible.
"""

