def main(argv: Sequence[str] | None = None) -> int:
    """`cctv-release bundle|inspect|override`."""
    import argparse

    parser = argparse.ArgumentParser(prog="cctv-release")
    sub = parser.add_subparsers(dest="command", required=True)

    bundle_p = sub.add_parser("bundle", help="assemble the release bundle and its checksums")
    bundle_p.add_argument("--repo", type=Path, default=Path("."))
    bundle_p.add_argument("--out", type=Path, default=Path("dist"))
    bundle_p.add_argument("--version", default=None)
    bundle_p.add_argument("--frigate-version", required=True)
    bundle_p.add_argument("--frigate-contract-verified", required=True)
    bundle_p.add_argument("--frigate-amd64", required=True)
    bundle_p.add_argument("--frigate-arm64", required=True)
    bundle_p.add_argument("--mosquitto", required=True)
    bundle_p.add_argument("--image-amd64", required=True)
    bundle_p.add_argument("--image-arm64", required=True)
    bundle_p.add_argument("--json", action="store_true")

    inspect_p = sub.add_parser("inspect", help="verify an assembled bundle")
    inspect_p.add_argument("archive", type=Path)
    inspect_p.add_argument("--json", action="store_true")

    override_p = sub.add_parser("override", help="write compose.override.yml from versions.yml")
    override_p.add_argument("manifest", type=Path)
    override_p.add_argument("--arch", required=True, choices=["amd64", "arm64"])
    override_p.add_argument("--compose", type=Path, default=Path("compose.yml"))
    override_p.add_argument("--target", default=None)

    args = parser.parse_args(argv)

    try:
        if args.command == "bundle":
            result = assemble(
                repo=args.repo,
                out_dir=args.out,
                version=args.version,
                images={"amd64": args.image_amd64, "arm64": args.image_arm64},
                frigate_version=args.frigate_version,
                frigate_contract_verified=args.frigate_contract_verified,
                frigate_images={"amd64": args.frigate_amd64, "arm64": args.frigate_arm64},
                mosquitto_image=args.mosquitto,
            )
            if args.json:
                print(json.dumps({**result.to_dict(), "sha256": dict(result.sha256)}, indent=2))
            else:
                print(f"{result.archive} ({result.bytes_written} bytes, {len(result.files)} files)")
            return 0

        if args.command == "inspect":
            checked = inspect(args.archive)
            if args.json:
                print(json.dumps(checked.to_dict(), indent=2))
            elif checked.ok:
                print(f"{args.archive}: {checked.version}, {len(checked.files)} files, all match")
            else:
                for problem in checked.problems:
                    print(f"cctv-release: {problem}", file=sys.stderr)
            return 0 if checked.ok else 1

        manifest = yaml.safe_load(args.manifest.read_text(encoding="utf-8")) or {}
        services = cctv_services(args.compose.read_text(encoding="utf-8"))
        print(
            override_for(manifest, arch=args.arch, services=services, target=args.target),
            end="",
        )
        return 0
    except ReleaseError as exc:
        print(f"cctv-release: {exc}", file=sys.stderr)
        return 78
    except (OSError, yaml.YAMLError) as exc:
        print(f"cctv-release: {exc}", file=sys.stderr)
        return 74
