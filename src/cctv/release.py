def strip_build_blocks(text: str) -> str:
    """Remove every `build:` block, and keep everything else byte for byte.

    Removed by line rather than by re-serialising the YAML, because the repository's compose file
    is heavily commented *on purpose* — those comments are the documentation an operator reads
    when a mount does not appear — and `yaml.dump` would delete all of them.

    The result is then parsed and compared against a parsed expectation, so a future `build:`
    written somewhere the line walker does not expect fails the release instead of shipping.
    """
    lines = text.splitlines(keepends=True)
    kept: list[str] = []
    index = 0
    while index < len(lines):
        line = lines[index]
        stripped = line.strip()
        if stripped == "build:" or stripped.startswith("build:"):
            indent = len(line) - len(line.lstrip())
            index += 1
            # Swallow the block: everything deeper than the `build:` key itself.
            while index < len(lines):
                following = lines[index]
                if not following.strip():
                    index += 1
                    continue
                deeper = len(following) - len(following.lstrip())
                if deeper <= indent:
                    break
                index += 1
            continue
        kept.append(line)
        index += 1
    return "".join(kept)


def _services(document: Mapping[str, Any]) -> Mapping[str, Any]:
    services = document.get("services")
    return services if isinstance(services, Mapping) else {}


def _shape(document: Mapping[str, Any]) -> dict[str, Any]:
    """The parts of a compose file a site depends on, for comparison.

    Names, images, mounts and ports — not comments, and not `build:`, which is the one thing the
    release is allowed to differ in.
    """
    shape: dict[str, Any] = {}
    for name, body in sorted(_services(document).items()):
        if not isinstance(body, Mapping):
            continue
        shape[name] = {
            "image": body.get("image"),
            "volumes": body.get("volumes"),
            "ports": body.get("ports"),
            "command": body.get("command"),
        }
    return shape


def derive_compose(source: str) -> str:
    """`compose.yml` → the release version: no `build:`, nothing else changed."""
    derived = strip_build_blocks(source)
    original = yaml.safe_load(source)
    result = yaml.safe_load(derived)
    if not isinstance(original, Mapping) or not isinstance(result, Mapping):
        raise ReleaseError("compose.yml did not parse as a mapping; refusing to derive")

    leftover = [
        name
        for name, body in {
            **_services(result),
            **{"x-cctv-image": result.get("x-cctv-image")},
        }.items()
        if isinstance(body, Mapping) and "build" in body
    ]
    if leftover:
        raise ReleaseError(
            "the derived compose file still has a build: block for "
            f"{', '.join(sorted(leftover))}. A release must pull, never build."
        )
    if _shape(original) != _shape(result):
        raise ReleaseError(
            "deriving the release compose file changed more than build:. "
            "Services, images, mounts or ports differ — fix the derivation rather than shipping "
            "a graph nobody reviewed."
        )
    return derived


