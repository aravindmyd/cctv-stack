def bundle_version(repo: Path) -> str:
    """The version, from `pyproject.toml`. One source, so a tag cannot disagree with a file."""
    import tomllib

    with (Path(repo) / "pyproject.toml").open("rb") as handle:
        return str(tomllib.load(handle)["project"]["version"])


def database_schema_version(repo: Path) -> int:
    """The newest migration on disk.

    Read rather than typed, which is the rule `packaging.md` §5 sets: a hand-written schema
    number in a manifest is a number that is wrong exactly once, on the release that added a
    migration.
    """
    migrations = Path(repo) / "src" / "cctv" / "migrations"
    versions = []
    for path in sorted(migrations.glob("*.sql")):
        prefix = path.stem.split("_", 1)[0]
        if prefix.isdigit():
            versions.append(int(prefix))
    if not versions:
        raise ReleaseError(f"no migrations found under {migrations}; refusing to guess a schema")
    return max(versions)


